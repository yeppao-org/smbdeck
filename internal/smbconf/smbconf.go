// Package smbconf renders smb.conf from values that have already been
// validated. It checks every value once more as it writes it (defense in
// depth): a value that could change the structure of the file makes Render
// fail instead of producing a file.
package smbconf

import (
	"fmt"
	"slices"
	"strings"

	"github.com/yeppao-org/smbdeck/internal/validate"
)

// Global holds the settings of the [global] section that vary per deployment.
type Global struct {
	// NetBIOSName is the server name (15 characters at most).
	NetBIOSName string
	// ServerString is the description clients may display.
	ServerString string
	Workgroup    string
	// HostsAllow lists the networks allowed to connect; empty means any
	// (authentication is still required).
	HostsAllow []string
	// PassdbPath is the smbpasswd file generated from the desired state.
	PassdbPath string
	// RunDir holds Samba's lock, state, cache and pid directories.
	RunDir string
	// LogLevel is Samba's debug level (0 to 10).
	LogLevel int
	// Signing is "mandatory" (the default when empty) or "auto".
	Signing string
}

// Share is one published share, fully resolved.
type Share struct {
	Name string
	// Path is absolute and resolved (no symbolic link left).
	Path        string
	ReadUsers   []string
	WriteUsers  []string
	FilesUser   string
	FilesGroup  string
	TimeMachine bool
	// TimeMachineMaxSize is empty or like "500G".
	TimeMachineMaxSize string
}

type writer struct {
	b   strings.Builder
	err error
}

func (w *writer) section(name string) {
	if w.err != nil {
		return
	}
	if !validate.SectionName(name) || name == "" {
		w.err = fmt.Errorf("smbconf: unsafe section name %q", name)
		return
	}
	fmt.Fprintf(&w.b, "\n[%s]\n", name)
}

func (w *writer) set(key, value string) {
	if w.err != nil {
		return
	}
	if !validate.ConfValue(value) {
		w.err = fmt.Errorf("smbconf: unsafe value for %q", key)
		return
	}
	fmt.Fprintf(&w.b, "\t%s = %s\n", key, value)
}

// setList writes a space-separated list. Each item is checked on its own: it
// must be a safe value and hold no separator (space, comma, quote).
func (w *writer) setList(key string, items []string) {
	if w.err != nil {
		return
	}
	for _, it := range items {
		if it == "" || !validate.ConfValue(it) || strings.ContainsAny(it, " ,\"\t") {
			w.err = fmt.Errorf("smbconf: unsafe item in %q", key)
			return
		}
	}
	w.set(key, strings.Join(items, " "))
}

func (w *writer) comment(text string) {
	if w.err != nil {
		return
	}
	for _, line := range strings.Split(text, "\n") {
		fmt.Fprintf(&w.b, "# %s\n", line)
	}
}

// Render returns the full smb.conf. Shares without any account are left out:
// in Samba, an empty "valid users" lets every account in, which is never what
// an empty access list means here.
func Render(g Global, shares []Share) ([]byte, error) {
	w := &writer{}
	w.comment("Generated by smbdeck from the desired state. Do not edit: it is rewritten on every change.")
	w.section("global")
	w.set("server role", "standalone server")
	w.set("security", "user")
	w.set("workgroup", g.Workgroup)
	w.set("netbios name", g.NetBIOSName)
	w.set("server string", g.ServerString)
	w.set("passdb backend", "smbpasswd:"+g.PassdbPath)

	// Protocols and authentication.
	w.set("server min protocol", "SMB2_10")
	w.set("server smb encrypt", "desired")
	w.set("restrict anonymous", "2")
	w.set("map to guest", "never")
	w.set("invalid users", "root")
	w.set("ntlm auth", "ntlmv2-only")
	signing := g.Signing
	if signing == "" {
		signing = "mandatory"
	}
	if signing != "mandatory" && signing != "auto" {
		w.err = fmt.Errorf("smbconf: server signing %q: want mandatory or auto", signing)
	}
	w.set("server signing", signing)
	// Passwords come from the desired state only: a change requested by an
	// SMB client would be written to the passdb, then silently undone at the
	// next pass. Refuse it instead.
	w.set("check password script", "/bin/false")
	w.set("unix password sync", "no")

	// Network: SMB over TCP 445 only, no NetBIOS, no printing.
	w.set("disable netbios", "yes")
	w.set("smb ports", "445")
	w.set("load printers", "no")
	w.set("printing", "bsd")
	w.set("printcap name", "/dev/null")
	w.set("disable spoolss", "yes")
	if len(g.HostsAllow) > 0 {
		w.setList("hosts allow", g.HostsAllow)
	}

	// File system: no link may lead outside a share; each account only sees
	// the shares it may open.
	w.set("wide links", "no")
	w.set("follow symlinks", "yes")
	w.set("unix extensions", "no")
	w.set("smb3 unix extensions", "no")
	w.set("access based share enum", "yes")

	// macOS interoperability.
	w.set("vfs objects", "catia fruit streams_xattr")
	w.set("fruit:metadata", "stream")
	w.set("fruit:model", "MacSamba")
	w.set("fruit:posix_rename", "yes")
	w.set("fruit:veto_appledouble", "no")
	w.set("fruit:nfs_aces", "no")
	w.set("fruit:wipe_intentionally_left_blank_rfork", "yes")
	w.set("fruit:delete_empty_adfiles", "yes")

	// Writable locations, all under one directory the agent owns.
	run := strings.TrimSuffix(g.RunDir, "/")
	w.set("lock directory", run+"/lock")
	w.set("state directory", run+"/state")
	w.set("cache directory", run+"/cache")
	w.set("pid directory", run+"/pid")
	w.set("ncalrpc dir", run+"/ncalrpc")
	w.set("private dir", run+"/private")
	// Logs go to stdout (smbd --debug-stdout); the log file setting only
	// places the core dump directory somewhere writable.
	w.set("log file", run+"/log/smbd.log")
	w.set("max log size", "1000")

	// Identities without a Unix account (none are expected) map into a range
	// far from every real UID.
	w.set("idmap config * : backend", "tdb")
	w.set("idmap config * : range", "1000000-1999999")

	w.set("log level", fmt.Sprint(clamp(g.LogLevel, 0, 10)))

	sorted := slices.Clone(shares)
	slices.SortFunc(sorted, func(a, b Share) int { return strings.Compare(strings.ToLower(a.Name), strings.ToLower(b.Name)) })
	for _, s := range sorted {
		renderShare(w, s)
	}
	if w.err != nil {
		return nil, w.err
	}
	return []byte(w.b.String()), nil
}

func renderShare(w *writer, s Share) {
	read := sortedUnique(s.ReadUsers)
	write := sortedUnique(s.WriteUsers)
	// An account listed in both gets write access: keep it in one list only.
	read = slices.DeleteFunc(read, func(u string) bool { return slices.Contains(write, u) })
	valid := sortedUnique(append(slices.Clone(read), write...))
	if len(valid) == 0 {
		return
	}
	for _, u := range valid {
		if validate.UserName(u) != validate.OK {
			w.err = fmt.Errorf("smbconf: unsafe account name in share %q", s.Name)
			return
		}
	}
	if !strings.HasPrefix(s.Path, "/") {
		w.err = fmt.Errorf("smbconf: share %q: path must be absolute", s.Name)
		return
	}
	if validate.ShareName(s.Name) != validate.OK {
		w.err = fmt.Errorf("smbconf: unsafe share name %q", s.Name)
		return
	}
	w.section(s.Name)
	w.set("path", s.Path)
	w.setList("valid users", valid)
	if len(read) > 0 {
		w.setList("read list", read)
	}
	if len(write) > 0 {
		w.setList("write list", write)
	}
	w.set("read only", "yes")
	w.set("browseable", "yes")
	w.set("guest ok", "no")
	w.set("force user", s.FilesUser)
	w.set("force group", s.FilesGroup)
	w.set("create mask", "0664")
	w.set("directory mask", "2775")
	if s.TimeMachine {
		w.set("fruit:time machine", "yes")
		if s.TimeMachineMaxSize != "" {
			if validate.TimeMachineSize(s.TimeMachineMaxSize) != validate.OK {
				w.err = fmt.Errorf("smbconf: share %q: invalid Time Machine size", s.Name)
				return
			}
			w.set("fruit:time machine max size", s.TimeMachineMaxSize)
		}
	}
}

func sortedUnique(in []string) []string {
	out := slices.Clone(in)
	slices.Sort(out)
	return slices.Compact(out)
}

func clamp(v, lo, hi int) int {
	return max(lo, min(v, hi))
}
