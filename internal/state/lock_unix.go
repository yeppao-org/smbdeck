//go:build unix

package state

import (
	"os"
	"path/filepath"
	"syscall"
)

// lockDir takes an exclusive lock on <dir>/.lock, so that two web processes
// sharing a state volume never interleave their read-modify-write cycles.
func lockDir(dir string) (func(), error) {
	f, err := os.OpenFile(filepath.Join(dir, ".lock"), os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return nil, err
	}
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX); err != nil {
		_ = f.Close()
		return nil, err
	}
	return func() {
		_ = syscall.Flock(int(f.Fd()), syscall.LOCK_UN)
		_ = f.Close()
	}, nil
}
